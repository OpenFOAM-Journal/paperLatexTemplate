"""Research helper: per-file version history of the OFJ template.

For every commit on the first-parent chain of master (= states that were
actually published on master), record the git blob id of each shipped file.
Collapse consecutive identical blobs into "file versions" with the date range
during which each version was current on master.  Also hash every blob ever
reachable (incl. feature-branch commits) so the checker can recognise them.

Usage: python mine_history.py <repo> <out_dir>
"""
import hashlib
import json
import subprocess
import sys
from pathlib import Path

SKIP_SUFFIX = (".pdf", ".log", ".bbl", ".png")
SKIP_PREFIX = (".github/", ".gitignore", "README.md")


def git(repo, *args):
    return subprocess.run(["git", "-C", repo, *args], check=True,
                          capture_output=True).stdout


def norm_hash(data: bytes) -> str:
    """Hash robust against CRLF, trailing whitespace and trailing blank lines."""
    text = data.replace(b"\r\n", b"\n").replace(b"\r", b"\n")
    lines = [ln.rstrip() for ln in text.split(b"\n")]
    while lines and not lines[-1]:
        lines.pop()
    return hashlib.sha256(b"\n".join(lines)).hexdigest()[:16]


def main(repo, out_dir):
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    log = git(repo, "log", "--first-parent", "--reverse",
              "--format=%H %h %ad %s", "--date=short", "master").decode()
    commits = [ln.split(" ", 3) for ln in log.strip().splitlines()]

    versions = {}  # path -> list of dicts
    for full, short, date, subj in commits:
        tree = git(repo, "ls-tree", "-r", full).decode().splitlines()
        present = {}
        for row in tree:
            meta, path = row.split("\t", 1)
            if path.endswith(SKIP_SUFFIX) or path.startswith(SKIP_PREFIX):
                continue
            present[path] = meta.split()[2]
        for path, blob in present.items():
            hist = versions.setdefault(path, [])
            if hist and hist[-1]["blob"] == blob and hist[-1]["until"] is None:
                continue
            if hist and hist[-1]["until"] is None:
                hist[-1]["until"] = date
                hist[-1]["until_commit"] = short
            hist.append({"blob": blob, "from": date, "from_commit": short,
                         "subject": subj, "until": None, "until_commit": None})
        for path, hist in versions.items():
            if path not in present and hist[-1]["until"] is None:
                hist[-1]["until"] = date
                hist[-1]["until_commit"] = short
                hist[-1]["removed"] = True

    for path, hist in versions.items():
        for v in hist:
            data = git(repo, "cat-file", "-p", v["blob"])
            v["norm"] = norm_hash(data)
            v["lines"] = data.count(b"\n")

    # every blob ever reachable, for the "known but never on master" case
    allblobs = {}
    revs = git(repo, "rev-list", "--all").decode().split()
    for rev in revs:
        for row in git(repo, "ls-tree", "-r", rev).decode().splitlines():
            meta, path = row.split("\t", 1)
            if path.endswith(SKIP_SUFFIX) or path.startswith(SKIP_PREFIX):
                continue
            allblobs.setdefault(path, set()).add(meta.split()[2])

    (out / "file_versions.json").write_text(json.dumps(versions, indent=1))
    md = ["# Template file versions on master (first-parent)\n",
          "Generated by mine_history.py. 'current until' = date the next "
          "version landed on master (open = still current).\n"]
    for path in sorted(versions):
        hist = versions[path]
        extra = len(allblobs.get(path, ())) - len({v["blob"] for v in hist})
        md.append(f"\n## `{path}` - {len(hist)} version(s) on master"
                  + (f", {extra} more only on branches" if extra > 0 else ""))
        md.append("\n| # | blob | from | until | lines | introduced by |")
        md.append("|---|---|---|---|---|---|")
        for i, v in enumerate(hist, 1):
            until = v["until"] or "open"
            if v.get("removed"):
                until += " (removed)"
            md.append(f"| {i} | `{v['blob'][:8]}` | {v['from']} | {until} | "
                      f"{v['lines']} | {v['from_commit']} {v['subject'][:60]} |")
    (out / "file_versions.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"{len(commits)} first-parent commits, {len(versions)} files")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
